class MathUtil {
    static add(a: number, b: number): number {
        return a + b
    }
    static sub(a: number, b: number): number {
        return a - b
    }
    static mul(a: number, b: number): number {
        return a * b
    }
    static div(a: number, b: number): number {
        return a / b
    }
}
console.log(MathUtil.add(2,3));
console.log(MathUtil.div(2,0));
